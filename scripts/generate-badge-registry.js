const fs = require('fs');
const path = require('path');

const BADGES_DIR = path.join(__dirname, '../assets/icons/badges');
const BADGE_SUBDIRS = [
  'mental-health-143/svg',
  'sport-215/svg',
  'stay-at-home-14 2/svg',
];
const REGISTRY_PATH = path.join(__dirname, '../src/components/icons/badgeIconRegistry.ts');

function normalizeName(file) {
  return file
    .replace('.svg', '')
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-');
}

function generateRegistry() {
  console.log('Generating Badge icon registry...');
  const entries = {};

  BADGE_SUBDIRS.forEach(subdir => {
    const dirPath = path.join(BADGES_DIR, subdir);
    console.log(`\nScanning: ${dirPath}`);

    if (!fs.existsSync(dirPath)) {
      console.warn(`  WARNING: directory not found, skipping`);
      return;
    }

    const files = fs.readdirSync(dirPath).filter(f => f.endsWith('.svg'));
    files.forEach(file => {
      const filePath = path.join(dirPath, file);
      const content = fs.readFileSync(filePath, 'utf-8').trim();
      const name = normalizeName(file);
      entries[name] = content;
      console.log(`  + ${name}`);
    });
  });

  const sortedKeys = Object.keys(entries).sort();
  let output = `/**\n * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY\n * Generated by scripts/generate-badge-registry.js\n */\n\nexport const BADGE_ICONS: Record<string, string> = {\n`;
  sortedKeys.forEach(key => {
    const escaped = entries[key].replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
    output += `  '${key}': \`${escaped}\`,\n`;
  });
  output += `};\n\nexport type BadgeIconName = keyof typeof BADGE_ICONS;\n`;

  fs.writeFileSync(REGISTRY_PATH, output);
  console.log(`\nGenerated ${sortedKeys.length} icons -> ${REGISTRY_PATH}`);
}

generateRegistry();
