const fs = require('fs');
const path = require('path');

const ICONSCOUT_DIR = path.join(__dirname, '../assets/Icons/NeatIcons');
const REGISTRY_PATH = path.join(__dirname, '../src/components/icons/iconScoutRegistry.ts');

function normalizeName(file) {
  return file
    .replace('.svg', '')
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-');
}

function generateRegistry() {
  console.log('Generating IconScout registry...');

  const entries = {};
  const files = fs.readdirSync(ICONSCOUT_DIR).filter(f => f.endsWith('.svg'));

  files.forEach(file => {
    const filePath = path.join(ICONSCOUT_DIR, file);
    const content = fs.readFileSync(filePath, 'utf-8').trim();
    const name = normalizeName(file);
    entries[name] = content;
    console.log(`  + ${name}`);
  });


  const sortedKeys = Object.keys(entries).sort();

  let output = `/**\n * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY\n * Generated by scripts/generate-iconscout-registry.js\n */\n\nexport const ICONSCOUT_ICONS: Record<string, string> = {\n`;

  sortedKeys.forEach(key => {
    const escaped = entries[key].replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
    output += `  '${key}': \`${escaped}\`,\n`;
  });

  output += `};\n\nexport type IconScoutName = keyof typeof ICONSCOUT_ICONS;\n`;

  fs.writeFileSync(REGISTRY_PATH, output);
  console.log(`\nGenerated ${sortedKeys.length} icons -> ${REGISTRY_PATH}`);
}

generateRegistry();
