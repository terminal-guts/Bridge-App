const fs = require('fs');
const path = require('path');

const ASSETS_DIR = path.join(__dirname, '../assets/iconscout');
const OUTPUT_FILE = path.join(__dirname, '../src/components/icons/iconScoutRegistry.ts');

function findSvgs(dir, fileList = []) {
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat.isDirectory()) {
      findSvgs(filePath, fileList);
    } else if (filePath.endsWith('.svg')) {
      fileList.push(filePath);
    }
  }
  return fileList;
}

function normalizeName(filename) {
  const base = path.basename(filename, '.svg');
  return base.toLowerCase().trim().replace(/[\s_]+/g, '-').replace(/-+/g, '-');
}

function generateRegistry() {
  const svgFiles = findSvgs(ASSETS_DIR);
  const registry = {};

  for (const file of svgFiles) {
    const name = normalizeName(file);
    const content = fs.readFileSync(file, 'utf8');
    // Remove formatting from SVG string
    registry[name] = content.replace(/\r?\n|\r/g, '').replace(/>\s+</g, '><');
  }

  // Ensure community is correctly spelled (fix PR review typo)
  if (registry['comminity']) {
      registry['community'] = registry['comminity'];
      delete registry['comminity'];
  }

  const iconNames = Object.keys(registry).map(name => `'${name}'`).join(' | ');

  const fileContent = `// Auto-generated by scripts/generate-iconscout-registry.js
// Do not edit this file directly.

export type IconScoutName = ${iconNames};

export const ICONSCOUT_ICONS: Record<string, string> = ${JSON.stringify(registry, null, 2)};
`;

  fs.writeFileSync(OUTPUT_FILE, fileContent);
  console.log(`Generated registry with ${svgFiles.length} icons.`);
}

generateRegistry();
